const SPLYTO_IOS_INSTALL_URL = 'https://testflight.apple.com/join/3gzeU4Zn';

function splyto_share_page_language(string $acceptLanguage): string
{
    $best = 'en';
    $bestQuality = 0.0;
    foreach (explode(',', $acceptLanguage) as $part) {
        $pieces = explode(';', trim($part));
        $language = strtolower(substr(trim($pieces[0]), 0, 2));
        // Norwegian is sent as no, nb or nn; the catalog has it as nb.
        if ($language === 'no' || $language === 'nn') {
            $language = 'nb';
        }
        $quality = 1.0;
        if (isset($pieces[1]) && preg_match('/^\s*q=([0-9.]+)\s*$/', $pieces[1], $match) === 1) {
            $quality = (float) $match[1];
        }
        if ($quality > $bestQuality && isset(SPLYTO_SHARE_PAGE_TEXT[$language])) {
            $best = $language;
            $bestQuality = $quality;
        }
    }
    return $best;
}

/** Install links by platform. iOS is TestFlight until the App Store listing exists. */
function splyto_app_install_links(): array
{
    $ios = trim(env_string('TRIP_IOS_INSTALL_URL', SPLYTO_IOS_INSTALL_URL));
    return [
        'ios' => str_starts_with($ios, 'https://') ? $ios : '',
        'android' => 'https://play.google.com/store/apps/details?id=com.tripsplit.app.tripsplit',
    ];
}

/** Comes before the shared page styles, because a browser uses the first of these it finds. */
function splyto_share_page_meta(): string
{
    return '<meta name="color-scheme" content="light">'
        . '<meta name="theme-color" content="#BFEFEA">';
}

function splyto_share_page_header(): string
{
    return '<img class="ribbons" src="/site/images/ribbons/hero.svg" alt="">'
        . '<div class="brand"><img src="/site/images/logo.svg" alt="Splyto" width="180" height="71"></div>';
}

