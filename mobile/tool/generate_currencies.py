#!/usr/bin/env python3
"""Generates the currency catalog for the app and the server. Run from mobile/.

Needs Babel, for CLDR's currency names and digits: pip install babel. This is a
development tool only. Then run `flutter gen-l10n`.
"""
import json
import re
from pathlib import Path

from babel.numbers import get_currency_name, get_currency_precision

ROOT = Path(__file__).resolve().parents[1]
LOCALES = {'en': 'en', 'lv': 'lv', 'de': 'de', 'es': 'es', 'fr': 'fr', 'it': 'it',
           'pt': 'pt_PT', 'pl': 'pl', 'nl': 'nl', 'sv': 'sv', 'da': 'da', 'nb': 'nb',
           'fi': 'fi', 'cs': 'cs', 'uk': 'uk'}

# Offered in this order. Each one is checked to have current and historical rates.
CURRENCIES = {
    'Europe': 'EUR:€ GBP:£ CHF:CHF NOK:kr SEK:kr DKK:kr PLN:zł CZK:Kč HUF:Ft RON:lei BGN:лв '
              'ISK:kr ALL:L BAM:KM BYN:Br MDL:L MKD:ден RSD:дин UAH:₴ GEL:₾ TRY:₺ RUB:₽',
    'Americas': 'USD:$ CAD:C$ MXN:MX$ BRL:R$ ARS:ARS CLP:CLP COP:COP PEN:S/ UYU:$U BOB:Bs '
                'PYG:₲ CRC:₡ DOP:RD$ GTQ:Q PAB:B/. HNL:L NIO:C$ JMD:J$ BBD:Bds$ BSD:B$ TTD:TT$ '
                'XCD:EC$ BZD:BZ$ AWG:Afl BMD:BD$ KYD:CI$',
    'Asia': 'JPY:¥ CNY:¥ KRW:₩ INR:₹ THB:฿ VND:₫ IDR:Rp MYR:RM SGD:S$ PHP:₱ HKD:HK$ TWD:NT$ '
            'LKR:Rs NPR:Rs BDT:৳ PKR:Rs KHR:៛ LAK:₭ MMK:K MNT:₮ MOP:MOP$ BND:B$ MVR:Rf '
            'BTN:Nu KZT:₸ UZS:UZS KGS:KGS TJS:SM AZN:₼ AMD:֏',
    'Middle East': 'AED:AED SAR:SAR QAR:QAR OMR:OMR KWD:KWD BHD:BHD JOD:JOD ILS:₪ LBP:LBP IQD:IQD',
    'Africa': 'ZAR:R EGP:E£ MAD:MAD TND:TND DZD:DZD KES:KSh TZS:TSh UGX:USh RWF:RF ETB:Br '
              'GHS:₵ NGN:₦ XOF:CFA XAF:FCFA MUR:Rs SCR:SR NAD:N$ BWP:P ZMW:ZK MZN:MT AOA:Kz '
              'MGA:Ar CVE:CVE GMD:D',
    'Oceania': 'AUD:A$ NZD:NZ$ FJD:FJ$ XPF:CFP WST:WS$ VUV:VT TOP:T$ PGK:K',
}

# Their subunits exist on paper but prices are never written with them.
NO_SUBUNIT_IN_PRACTICE = {'HUF', 'IDR', 'COP', 'LAK', 'MMK', 'UZS', 'TZS', 'LBP', 'IQD', 'MGA', 'KHR'}


def digits(code):
    if code in NO_SUBUNIT_IN_PRACTICE:
        return 0
    # Amounts are stored in hundredths, so currencies with three digits show two.
    return min(get_currency_precision(code), 2)


def name(code, locale):
    text = get_currency_name(code, locale=locale)
    return text[:1].upper() + text[1:]


def entries():
    items = [item.split(':', 1) for group in CURRENCIES.values() for item in group.split()]
    codes = [code for code, _ in items]
    assert len(codes) == 120, len(codes)
    assert len(set(codes)) == 120
    return items


def write_arb(items):
    for language, locale in LOCALES.items():
        path = ROOT / f'lib/l10n/app_{language}.arb'
        text = path.read_text()
        data = json.loads(text)
        added = ''.join(
            f'  {json.dumps(key)}: {json.dumps(name(code, locale), ensure_ascii=False)},\n'
            for code, _ in items
            for key in [f'currencyName{code.capitalize()}']
            if key not in data
        )
        if added:
            match = re.search(r'^  "currencyNameAud": "[^\n]*",\n', text, re.M)
            text = text[:match.end()] + added + text[match.end():]
            json.loads(text)
            path.write_text(text)


def write_dart(items):
    options = ''.join(
        f"  AppCurrencyOption(code: '{code}', symbol: {dart_string(symbol)}"
        + (f', decimalDigits: {digits(code)}' if digits(code) != 2 else '')
        + '),\n'
        for code, symbol in items
    )
    labels = ''.join(
        f"    '{code}' => l10n.currencyName{code.capitalize()},\n" for code, _ in items
    )
    (ROOT / 'lib/core/currency/app_currency_data.g.dart').write_text(
        '// Generated by tool/generate_currencies.py. Do not edit.\n'
        "part of 'app_currency.dart';\n\n"
        'const List<AppCurrencyOption> _catalog = <AppCurrencyOption>[\n'
        f'{options}];\n\n'
        'String? _generatedLabel(String code, AppLocalizations l10n) => switch (code) {\n'
        f'{labels}    _ => null,\n}};\n'
    )


def dart_string(value):
    escaped = value.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    return f"'{escaped}'"


def write_php(items):
    def rows(values):
        values = list(values)
        return ''.join(
            "    " + ', '.join(f"'{c}'" for c in values[i:i + 12]) + ",\n"
            for i in range(0, len(values), 12)
        )

    no_decimals = [code for code, _ in items if digits(code) == 0]
    (ROOT.parent / 'api/lib/helpers/helper_currency_catalog.php').write_text(
        '<?php\ndeclare(strict_types=1);\n\n'
        '// Generated by mobile/tool/generate_currencies.py. Do not edit.\n\n'
        'const TRIP_SUPPORTED_CURRENCY_CODES = [\n' + rows(c for c, _ in items) + '];\n\n'
        'const CURRENCY_CODES_WITHOUT_DECIMALS = [\n' + rows(no_decimals) + '];\n'
    )


def main():
    items = entries()
    write_arb(items)
    write_dart(items)
    write_php(items)
    print(len(items), 'currencies;', sum(digits(c) == 0 for c, _ in items), 'without decimals')


main()
